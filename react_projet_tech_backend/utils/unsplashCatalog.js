function hashSeed(value) {
  let hash = 0;
  const text = String(value || '');
  for (let i = 0; i < text.length; i += 1) {
    hash = (hash << 5) - hash + text.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash) || 1;
}

function matchKnownSlug(value) {
  const normalized = String(value || '').toLowerCase();
  if (!normalized) return null;
  if (SLUG_TO_GROUP[normalized]) return SLUG_TO_GROUP[normalized];

  for (const slug of SORTED_SLUGS) {
    if (normalized === slug || normalized.startsWith(`${slug}-`)) {
      return SLUG_TO_GROUP[slug];
    }
  }
  return null;
}

export function resolvePhotoGroup(entity = {}) {
  const fromCategory = matchKnownSlug(entity.category_slug);
  if (fromCategory) return fromCategory;

  const fromProductSlug = matchKnownSlug(entity.slug);
  if (fromProductSlug) return fromProductSlug;

  const haystack = [entity.name, entity.short_description, entity.category_name, entity.subCategory]
    .filter(Boolean)
    .join(' ')
    .toLowerCase();

  for (const { group, keywords } of KEYWORD_GROUPS) {
    if (keywords.some(keyword => haystack.includes(keyword))) {
      return group;
    }
  }

  return 'default';
}

export function pickPhotoId(entity = {}, group) {
  const pool = PHOTO_POOLS[group] || PHOTO_POOLS.default;
  const seed = hashSeed(`${group}:${entity.id || ''}:${entity.slug || entity.name || ''}`);
  return pool[seed % pool.length];
}

export function buildSearchQuery(entity = {}) {
  const group = resolvePhotoGroup(entity);
  const name = String(entity.name || entity.slug || group).replace(/[-_]+/g, ' ');
  return `${name} ${group} product`.trim();
}
